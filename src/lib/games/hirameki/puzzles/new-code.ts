/** 矢印は a から b へ、どちらの字の枠にも重ならないよう両端を縮めて引く */
function arrow(a: [number, number], b: [number, number]): Shape {
  const gap = (p: [number, number]) => (p[0] === 150 && p[1] === 110 ? 32 : 28);
  const len = Math.hypot(b[0] - a[0], b[1] - a[1]);
  const [ux, uy] = [(b[0] - a[0]) / len, (b[1] - a[1]) / len];
  const [x1, y1] = [a[0] + ux * gap(a), a[1] + uy * gap(a)];
  const [x2, y2] = [b[0] - ux * gap(b), b[1] - uy * gap(b)];
  return g(
    '',
    line(x1, y1, x2 - ux * 8, y2 - uy * 8, { 'stroke-width': 3 }),
    poly(
      [
        [x2, y2],
        [x2 - ux * 12 - uy * 7, y2 - uy * 12 + ux * 7],
        [x2 - ux * 12 + uy * 7, y2 - uy * 12 - ux * 7]
      ],
      LINE
    )
  );
}

