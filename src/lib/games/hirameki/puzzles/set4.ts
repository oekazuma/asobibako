/** 真ん中から 12 時の向きを 0 にして、時計回りに deg 度の先 */
const hand = (cx: number, cy: number, deg: number, len: number, width: number) =>
  line(cx, cy, cx + len * Math.sin((deg * Math.PI) / 180), cy - len * Math.cos((deg * Math.PI) / 180), {
    'stroke-width': width
  });

const clock = (cx: number, cy: number, r: number, hour: number, minute: number, nums: [number, string][]): Shape[] => [
  circle(cx, cy, r, '#fff', { 'stroke-width': 3 }),
  ...Array.from({ length: 12 }, (_, i) => {
    const a = (i * Math.PI) / 6;
    const inner = i % 3 === 0 ? r - 11 : r - 7;
    return line(
      cx + inner * Math.sin(a),
      cy - inner * Math.cos(a),
      cx + (r - 3) * Math.sin(a),
      cy - (r - 3) * Math.cos(a)
    );
  }),
  ...nums.map(([h, t]) => {
    const a = (h * Math.PI) / 6;
    return text(cx + (r - 25) * Math.sin(a), cy - (r - 25) * Math.cos(a), t, 16);
  }),
  hand(cx, cy, minute * 6, r - 34, 3),
  hand(cx, cy, hour * 30 + minute / 2, r - 50, 6),
  circle(cx, cy, 4, LINE)
];

/** 4 × 4 × 4 の見取り図。(x, y, z) は 0..4 で、z が上。床の上に置いてある */
const iso = (x: number, y: number, z: number): [number, number] => [150 + (x - y) * 20, 112 + (x + y) * 11.5 - z * 23];
const cubeOnFloor = (): Shape[] => {
  const out: Shape[] = [
    poly([iso(-1.2, -1.2, 0), iso(5.6, -1.2, 0), iso(5.6, 5.6, 0), iso(-1.2, 5.6, 0)], '#eadfd2', { stroke: 'none' })
  ];
  for (let a = 0; a < 4; a++)
    for (let b = 0; b < 4; b++) {
      out.push(poly([iso(a, b, 4), iso(a + 1, b, 4), iso(a + 1, b + 1, 4), iso(a, b + 1, 4)], '#ffe08a'));
      out.push(poly([iso(4, a, b), iso(4, a + 1, b), iso(4, a + 1, b + 1), iso(4, a, b + 1)], '#a8d8ff'));
      out.push(poly([iso(a, 4, b), iso(a + 1, 4, b), iso(a + 1, 4, b + 1), iso(a, 4, b + 1)], '#ffb3c7'));
    }
  return out;
};

