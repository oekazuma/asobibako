/** 歯の向きは どの組も かみあう位置にそろえてある（ずれると 絵の上で歯がぶつかって見える） */
function gear(cx: number, cy: number, fill: string) {
  const pts: [number, number][] = [];
  const at = (r: number, deg: number): [number, number] => [
    Math.round((cx + r * Math.cos((deg * Math.PI) / 180)) * 10) / 10,
    Math.round((cy + r * Math.sin((deg * Math.PI) / 180)) * 10) / 10
  ];
  for (let t = 7.5; t < 360; t += 30) pts.push(at(34, t - 10), at(46, t - 5), at(46, t + 5), at(34, t + 10));
  return g('', poly(pts, fill), circle(cx, cy, 10, '#fff'));
}

