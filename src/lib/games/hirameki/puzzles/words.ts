/** a から b へ、枠 (半幅 hw, 半高 hh) のふちから少し離して矢印を引く */
function arrow(a: [number, number], b: [number, number], hw: number, hh: number): Shape {
  const [dx, dy] = [b[0] - a[0], b[1] - a[1]];
  const len = Math.hypot(dx, dy);
  const [ux, uy] = [dx / len, dy / len];
  const gap = Math.min(hw / Math.abs(ux || 1e-9), hh / Math.abs(uy || 1e-9)) + 5;
  const at = (t: number): [number, number] => [a[0] + ux * t, a[1] + uy * t];
  const [x1, y1] = at(gap);
  const [x2, y2] = at(len - gap);
  return g(
    '',
    line(x1, y1, x2 - ux * 6, y2 - uy * 6, { 'stroke-width': 2.5 }),
    poly(
      [
        [x2, y2],
        [x2 - ux * 11 - uy * 6, y2 - uy * 11 + ux * 6],
        [x2 - ux * 11 + uy * 6, y2 - uy * 11 - ux * 6]
      ],
      LINE
    )
  );
}

